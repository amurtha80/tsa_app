library(duckdb); library(DBI); library(lubridate)
con <- dbConnect(duckdb::duckdb())
now_est <- now(tzone='EST')
cat('R value (EST display):', format(now_est), ' tzone attr:', attr(now_est,'tzone'), '\n')
df <- data.frame(dt = now_est)
dbWriteTable(con, "scratch", df, overwrite = TRUE)
back <- dbGetQuery(con, "SELECT dt FROM scratch")
cat('Round-tripped naive TIMESTAMP value:', format(back$dt), '\n')
dbDisconnect(con, shutdown=TRUE)
